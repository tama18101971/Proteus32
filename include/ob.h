/**
 * @file ob.h
 * @brief Заголовочный файл модуля работы с Option Bytes контроллера CH32V003
 *
 * Модуль предоставляет интерфейс для хранения пользовательских данных
 * в области Option Bytes (OB) микроконтроллера CH32V003F4P6.
 *
 * Данные хранятся в кэше (_cache) в ОЗУ и синхронизируются с flash
 * при вызове ob_Flush(). Это позволяет избежать частой записи в flash
 * и продлить срок службы контроллера.
 *
 * Область OB расположена по адресу 0x1FFFF800. Стандартные регистры
 * (RDPR, USER, Data0, Data1, WRPR0, WRPR1) занимают 12 байт.
 * Пользовательские данные начинаются с OB_BASE + 16 (0x1FFFF810).
 *
 * Раскладка пользовательских данных (каждое поле — 2 байта адреса):
 *   +0  : magic   — маркер валидности (0xA5)
 *   +2  : tc      — целочисленный счётчик (int8_t)
 *   +4  : vc      — целочисленный счётчик (int8_t)
 *   +6  : ml      — беззнаковый байт (uint8_t)
 *   +8..+27 : slots[0..9] — массив из 10 байт для пользовательских данных
 *
 * Итого: 14 логических полей, 28 байт адресного пространства.
 */

#ifndef OB_H
#define OB_H

#include <stdint.h>
#include <stdbool.h>

/**
 * @brief Количество элементов в массиве slots[]
 *
 * Определяет размер пользовательского массива для хранения
 * произвольных байтовых данных в Option Bytes.
 */
#define SLOTS_COUNT 10

/**
 * @brief Инициализация модуля Option Bytes
 *
 * Считывает данные из flash-области Option Bytes в кэш.
 * Если magic-маркер не совпадает (первый запуск или повреждение),
 * все поля кэша обнуляются.
 *
 * @return true — данные валидны (magic == 0xA5)
 * @return false — данные невалидны, кэш обнулён
 */
bool ob_Init(void);

/**
 * @brief Проверка валидности данных в кэше
 *
 * @return true — magic-маркер совпадает
 * @return false — данные невалидны
 */
bool ob_IsValid(void);

/**
 * @brief Получение значения счётчика tc
 * @return Текущее значение tc (int8_t)
 */
int8_t ob_GetTc(void);

/**
 * @brief Получение значения счётчика vc
 * @return Текущее значение vc (int8_t)
 */
int8_t ob_GetVc(void);

/**
 * @brief Получение значения ml
 * @return Текущее значение ml (uint8_t)
 */
uint8_t ob_GetMl(void);

/**
 * @brief Установка значения счётчика tc
 * @param value Новое значение tc
 */
void ob_SetTc(int8_t value);

/**
 * @brief Установка значения счётчика vc
 * @param value Новое значение vc
 */
void ob_SetVc(int8_t value);

/**
 * @brief Установка значения ml
 * @param value Новое значение ml
 */
void ob_SetMl(uint8_t value);

/**
 * @brief Чтение элемента массива slots[] по индексу
 *
 * @param index Индекс элемента (0..SLOTS_COUNT-1)
 * @return Значение элемента или 0 при выходе за границы
 */
uint8_t ob_GetSlot(uint8_t index);

/**
 * @brief Запись элемента массива slots[] по индексу
 *
 * @param index Индекс элемента (0..SLOTS_COUNT-1)
 * @param value Новое значение элемента
 */
void ob_SetSlot(uint8_t index, uint8_t value);

/**
 * @brief Сброс кэша Option Bytes к заводским значениям
 *
 * Помечает кэш грязным; запись в flash выполняется при
 * ближайшем вызове ob_Flush() (5-секундный тик персистентности).
 */
void ob_ResetToDefaults(void);

/**
 * @brief Сохранение кэша в flash и верификация
 *
 * Перед записью устанавливает magic-маркер (0xA5), помечая
 * данные как валидные. Это позволяет сеттерам работать без
 * побочных эффектов — они лишь обновляют кэш.
 *
 * Выполняет полный цикл записи:
 * 1. Установка magic-маркера
 * 2. Стирание option bytes
 * 3. Запись стандартных регистров (RDPR, USER, Data0, Data1, WRPR0, WRPR1)
 * 4. Запись пользовательских данных (magic, tc, vc, ml, slots[])
 * 5. Чтение обратно и сравнение с кэшем
 *
 * @return true — все данные записаны и верифицированы
 * @return false — ошибка записи или верификации
 */
bool ob_Flush(void);

#endif // OB_H

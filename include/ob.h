/**
 * @file ob.h
 * @brief Оверлей пользовательских данных в Option Bytes (WL_FLASH v2.2.0)
 *
 * Модуль предоставляет доступ к пользовательским данным в области
 * Option Bytes микроконтроллера CH32V003F4U6 через wl_ob_* модуль
 * библиотеки WL_FLASH (libs/WL_FLASH). Собственного кода работы
 * с регистрами flash-контроллера здесь больше нет: чтение, стирание,
 * восстановление стандартных регистров и верификация выполняет
 * wl_hal_ob_program() внутри библиотеки.
 *
 * Данные живут в кэше в ОЗУ (обращение — OB_CFG->поле), синхронизация
 * с flash — wl_ob_mark_dirty() после изменения и (void)wl_ob_flush()
 * в 5-секундном тике персистентности (main.c). Flush без реального
 * изменения данных стирает страницу (сравнение с флешем), а запрос
 * dirty из прерывания в середине записи не теряется.
 *
 * Область OB: 0x1FFFF800. Стандартные регистры (RDPR, USER, Data0,
 * Data1, WRPR0, WRPR1) занимают 12 байт; пользовательские данные —
 * с OB_BASE + 16 (0x1FFFF810), байт i по адресу +i*2, значение в
 * младшем байте полуслова.
 *
 * Раскладка пользовательских данных (каждое поле — 2 байта адреса):
 *   +0  : magic   — маркер валидности (0xA5)
 *   +2  : tc      — поправка калибровки температуры (int8_t)
 *   +4  : vc      — поправка калибровки напряжения (int8_t)
 *   +6  : ml      — лунный уровень (uint8_t)
 *
 * Раскладка совпадает со старым standalone-драйвером (ob.c до v2.2
 * Proteus32), поэтому данные, записанные прежней прошивкой, загружаются
 * без миграции.
 *
 * Идиома изменения поля:
 *
 *     OB_CFG->tc = new_tc;
 *     wl_ob_mark_dirty();      // можно и из прерывания
 *
 * Запись без фактического изменения безопасна: flush сравнит кэш
 * с флешем и не потратит цикл стирания.
 *
 * @warning Аппаратная особенность CH32V003: стирание Option Bytes (OPTER)
 * стирает страницу целиком (включая RDPR/USER/Data0/Data1/WRPR0/WRPR1).
 * Пропадание питания между стиранием и программированием оставляет всю
 * область неопределённой (USER=0xFF меняет конфигурацию IWDG/NRST).
 * Поэтому в OB хранятся только редко меняемые калибровочные параметры,
 * валидность проверяется по magic-байту на старте, а динамические
 * настройки живут в WL_FLASH.
 */

#ifndef OB_H
#define OB_H

#include <stdbool.h>
#include <stdint.h>

#include "wl_flash_ob.h"

typedef struct {
    uint8_t magic;  /* 0xA5 — данные когда-либо записывались */
    int8_t  tc;     /* поправка калибровки температуры */
    int8_t  vc;     /* поправка калибровки напряжения */
    uint8_t ml;     /* лунный уровень, 0..8 */
} app_ob_t;

WL_OB_ASSERT_FITS(app_ob_t);

/* Доступ к кэшу Option Bytes: OB_CFG->tc = -3; */
#define OB_CFG WL_OB_DATA(app_ob_t)

#define OB_MAGIC 0xA5

/** Дефолты калибровки. */
static inline void ob_apply_defaults(void)
{
    OB_CFG->magic = OB_MAGIC;
    OB_CFG->tc    = 0;
    OB_CFG->vc    = 0;
    OB_CFG->ml    = 4;
}

/**
 * @brief Инициализация: чтение OB-области в кэш.
 *
 * Если magic-маркер отсутствует (первый запуск или потерянный flush),
 * кэш заполняется дефолтами; на флеш они попадут при ближайшем
 * (void)wl_ob_flush() — как и раньше, по тику персистентности после
 * первого реального изменения.
 *
 * @return true — данные валидны (magic == OB_MAGIC)
 * @return false — данные невалидны, кэш заполнен дефолтами
 */
static inline bool ob_Init(void)
{
    wl_ob_init();

    if (OB_CFG->magic != OB_MAGIC)
    {
        ob_apply_defaults();
        return false;
    }
    return true;
}

/**
 * @brief Сброс калибровки к заводским значениям.
 *
 * Кэш заполняется дефолтами и помечается грязным; запись на флеш
 * выполнит ближайший (void)wl_ob_flush() (5-секундный тик).
 */
static inline void ob_ResetToDefaults(void)
{
    ob_apply_defaults();
    wl_ob_mark_dirty();
}

#endif // OB_H